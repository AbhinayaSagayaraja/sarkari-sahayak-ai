/** Build a translator for one language: t("a.b", {x: 1}) with English fallback. */
export function translator(lang) {
  const lookup = (table, key) => key.split(".").reduce((o, k) => (o == null ? undefined : o[k]), table);
  const t = (key, vars = {}) => {
    const raw = lookup(STRINGS[lang], key) ?? lookup(STRINGS.en, key) ?? key;
    return typeof raw === "string" ? raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : raw;
  };
  t.lang = lang;
  t.scheme = (id) => SCHEME_NAMES[lang][id] || SCHEME_NAMES.en[id] || id;
  return t;
}
